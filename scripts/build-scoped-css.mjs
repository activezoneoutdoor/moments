// Generates the scoped stylesheets for the event pages and the team sections of My account from the panel
// stylesheet (styles/panels.css), re-themed with the website's fonts and colour tokens (app/(site)/site.css).
// Run after changing styles/panels.css: node scripts/build-scoped-css.mjs
import fs from "node:fs";
import postcss from "postcss";

const SOURCE = "styles/panels.css";

// Classes used by the public pages (events list, event page, booking, upload, lightbox).
const PUBLIC_CLASSES = new Set(`album-section attention auth-notice booking-card booking-details booking-done booking-form
  booking-intro booking-message booking-section closed cover-fallback danger drop-zone due empty-panel empty-state
  event-card event-cards event-cover event-description event-facts event-hero event-hero-image event-meta eyebrow
  form-actions form-grid form-hint ghost-button lightbox lightbox-close lightbox-credit lightbox-media lightbox-nav
  link-button link-text media-grid media-thumb next open paid pay-button payment-box pill prev primary-button progress
  section-heading small span-2 status-cancelled status-dot status-published upload-card upload-item upload-list
  upload-name upload-page upload-state upload-status upload-status-actions video-badge welcome wide year-chips
  config-note`.split(/\s+/).filter(Boolean));

// The old standalone admin's page frame (sign-in screen, top bar, footer, sub-menu). My account uses the website's
// header, footer and sign-in instead, so these rules are left out of the team sections.
const RETIRED_CLASSES = new Set(`login-shell loading-shell login-card brand-mark intro google-button access-note lock-icon
  config-note auth-notice domain-note visual-panel sun mountain mountain-back mountain-front photo-caption image-credit
  workspace-shell topbar wordmark account avatar account-details account-name account-email sign-out welcome
  workspace-footer topbar-link public-nav admin-link back-link code-sign-in code-actions role-pill admin-tabs
  source-intro source-grid source-card source-icon drive-icon photos-icon source-copy public-gallery-note gallery-dot
  album-card album-art album-ridge album-info soon coming-label`.split(/\s+/).filter(Boolean));

const classesOf = (selector) => [...selector.matchAll(/\.([a-z][a-z0-9-]*)/g)].map((m) => m[1]);

const TARGETS = [
  {
    scope: ".azo-public",
    out: "app/components/public/public-events.css",
    what: "Public event pages (/events/, /event/, /booking/, /upload/)",
    keep: (selector) => classesOf(selector).some((c) => PUBLIC_CLASSES.has(c)),
    page: ".azo-public{background:var(--bg);padding:calc(var(--header-h) + 32px) 0 64px;min-height:70vh}\n",
  },
  {
    scope: ".azo-admin",
    out: "app/components/account/admin.css",
    what: "Team sections of My account (/account/: Events, Albums, Members, Users)",
    keep: (selector) => {
      const classes = classesOf(selector);
      return classes.length > 0 && !classes.some((c) => RETIRED_CLASSES.has(c));
    },
    page: "",
  },
];

// Panel fonts and colours → website tokens.
const REPLACE = [
  [/'DM Sans',\s*sans-serif/g, "var(--font-body)"],
  [/'DM Sans'/g, "var(--font-body)"],
  [/Manrope,\s*sans-serif/g, "var(--font-head)"],
  [/\bManrope\b/g, "var(--font-head)"],
  [/background:\s*(#fff|white)\b/g, "background:var(--surface)"],
  [/#e3e7de|#e9ece5|#d5dccf|#d9dfd2|#e1e6da/g, "var(--border)"],
  [/#fcfdfa|#f6f7f1|#f7f8f3/g, "var(--bg)"],
];

function build({ scope, out, what, keep, page }) {
  const root = postcss.parse(fs.readFileSync(SOURCE, "utf8"));
  root.walkAtRules("import", (r) => r.remove());
  root.walkComments((c) => c.remove());
  root.walkRules((rule) => {
    if (rule.parent.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
    const selectors = rule.selectors.filter(keep);
    if (!selectors.length) return rule.remove();
    rule.selectors = selectors.map((s) => `${scope} ${s}`);
  });
  root.walkAtRules((r) => { if (r.name === "media" && !r.nodes?.length) r.remove(); });

  let css = root.toString();
  for (const [from, to] of REPLACE) css = css.replace(from, to);

  const header = `/* GENERATED by scripts/build-scoped-css.mjs from styles/panels.css. Do not edit by hand. */
/* ${what} in the website's look: the panel layout, scoped under ${scope}, with the website's fonts and colour tokens. */
${scope}{
  --ink:var(--text);--muted:var(--text-muted);--paper:var(--bg);--line:var(--border);
  --green:var(--primary);--lime:var(--accent);
  color:var(--text);font-family:var(--font-body);
}
${scope} h1,${scope} h2,${scope} h3{font-family:var(--font-head);color:var(--text)}
${scope} button,${scope} input,${scope} select,${scope} textarea{font-family:inherit}
`;
  // The panels' colours are made for a light background, so they stay light in dark mode (the website header and
  // footer still follow the visitor's setting).
  const footer = `
@media (prefers-color-scheme: dark){
  ${scope}{--text:#16241f;--text-muted:#4d5c56;--bg:#fbf8f2;--bg-tint:#f3ede1;--surface:#fff;--border:#e3ddd0;--primary:#0f3d2e;--accent:#f4a261}
}
${page}${scope} .eyebrow{color:var(--sun-600);letter-spacing:.14em}
`;
  fs.mkdirSync(out.slice(0, out.lastIndexOf("/")), { recursive: true });
  fs.writeFileSync(out, header + css.replace(/\n{3,}/g, "\n\n") + footer);
  console.log(`wrote ${out}: ${css.length} bytes`);
}

TARGETS.forEach(build);
