// Generates app/components/public/public-events.css from the admin stylesheet (app/(moments)/styles.css):
// only the rules the public event pages use, scoped under .azo-public and re-themed with the website's fonts and
// colour tokens (app/(site)/site.css). Run after changing styles the public pages share: node scripts/build-public-css.mjs
import fs from "node:fs";
import postcss from "postcss";

const SOURCE = "app/(moments)/styles.css";
const OUT = "app/components/public/public-events.css";
const SCOPE = ".azo-public";

// Classes used by the public pages (events list, event page, booking, upload, lightbox).
const PUBLIC_CLASSES = new Set(`album-section attention auth-notice booking-card booking-details booking-done booking-form
  booking-intro booking-message booking-section closed cover-fallback danger drop-zone due empty-panel empty-state
  event-card event-cards event-cover event-description event-facts event-hero event-hero-image event-meta eyebrow
  form-actions form-grid form-hint ghost-button lightbox lightbox-close lightbox-credit lightbox-media lightbox-nav
  link-button link-text media-grid media-thumb next open paid pay-button payment-box pill prev primary-button progress
  section-heading small span-2 status-cancelled status-dot status-published upload-card upload-item upload-list
  upload-name upload-page upload-state upload-status upload-status-actions video-badge welcome wide year-chips
  config-note`.split(/\s+/).filter(Boolean));

// Moments fonts and colours → website tokens.
const REPLACE = [
  [/'DM Sans',\s*sans-serif/g, "var(--font-body)"],
  [/Manrope,\s*sans-serif/g, "var(--font-head)"],
  [/\bManrope\b/g, "var(--font-head)"],
  [/background:\s*(#fff|white)\b/g, "background:var(--surface)"],
  [/#e3e7de|#e9ece5|#d5dccf|#d9dfd2|#e1e6da/g, "var(--border)"],
  [/#fcfdfa|#f6f7f1|#f7f8f3/g, "var(--bg)"],
];

const root = postcss.parse(fs.readFileSync(SOURCE, "utf8"));
const usesPublicClass = (selector) => [...selector.matchAll(/\.([a-z][a-z0-9-]*)/g)].some((m) => PUBLIC_CLASSES.has(m[1]));

root.walkAtRules("import", (r) => r.remove());
root.walkComments((c) => c.remove());
root.walkRules((rule) => {
  if (rule.parent.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
  const selectors = rule.selectors.filter(usesPublicClass);
  if (!selectors.length) return rule.remove();
  rule.selectors = selectors.map((s) => `${SCOPE} ${s}`);
});
root.walkAtRules((r) => { if (r.name === "media" && !r.nodes?.length) r.remove(); });

let css = root.toString();
for (const [from, to] of REPLACE) css = css.replace(from, to);

const header = `/* GENERATED by scripts/build-public-css.mjs from app/(moments)/styles.css. Do not edit by hand. */
/* Public event pages (/events/, /event/, /booking/, /upload/) in the website's look: Moments' page layout, scoped
   under ${SCOPE}, with the website's fonts and colour tokens. */
${SCOPE}{
  --ink:var(--text);--muted:var(--text-muted);--paper:var(--bg);--line:var(--border);
  --green:var(--primary);--lime:var(--accent);
  color:var(--text);font-family:var(--font-body);
}
${SCOPE} h1,${SCOPE} h2,${SCOPE} h3{font-family:var(--font-head);color:var(--text)}
`;
// Page-level rules for the event pages, added after the generated part.
const footer = `
/* The event pages' colours are made for a light background, so their content stays light in dark mode
   (the website header and footer still follow the visitor's setting). */
@media (prefers-color-scheme: dark){
  .azo-public{--text:#16241f;--text-muted:#4d5c56;--bg:#fbf8f2;--bg-tint:#f3ede1;--surface:#fff;--border:#e3ddd0;--primary:#0f3d2e;--accent:#f4a261}
}
.azo-public{background:var(--bg);padding:calc(var(--header-h) + 32px) 0 64px;min-height:70vh}
.azo-public .eyebrow{color:var(--sun-600);letter-spacing:.14em}
`;

fs.mkdirSync("app/components/public", { recursive: true });
fs.writeFileSync(OUT, header + css.replace(/\n{3,}/g, "\n\n") + footer);
console.log(`wrote ${OUT}: ${css.length} bytes`);
